import assert from 'node:assert/strict'
import { mkdtemp, rm, mkdir, writeFile, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { build } from 'esbuild'
const built = await build({stdin:{contents:"export { AtlasStore } from './src/host/store.ts'",resolveDir:process.cwd()},bundle:true,write:false,platform:'node',format:'esm'})
const {AtlasStore} = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`)
const root = await mkdtemp(join(tmpdir(),'atlas-trash-'))
try {
 const store = new AtlasStore(root)
 const w = await store.createWorkspace('trash-test')
 const add = async (title,parentId) => (await store.createNode({workspaceId:w.id,title,parentId})).node
 const parent = await add('root')
 const child = await add('child',parent.id)
 const grandchild = await add('grandchild',child.id)
 const sibling = await add('sibling',parent.id)
 await store.bindSession(child.id,'original-session')
 await store.appendMessage(child.threadId,'user','original evidence')
 const messageFile=join(root,'workspaces',w.id,'threads',`${child.threadId}.jsonl`)
 const messages=await readFile(messageFile,'utf8')
 const cards=join(root,'workspaces',w.id,'cards')
 await mkdir(cards,{recursive:true})
 const cardFile=join(cards,`${child.id}.json`)
 const card=JSON.stringify({id:'fixture-card',nodeId:child.id,tldr:'retained card',points:[]})
 await writeFile(cardFile,card)
 const dir=join(root,'session-workspaces',child.id)
 await mkdir(dir,{recursive:true});await writeFile(join(dir,'result.txt'),'original file')
 let preview=await store.deletionPreview(child.id)
 await add('new descendant',child.id)
 await assert.rejects(store.deleteNode(child.id,preview.token),/E_CONFLICT/)
 assert.equal((await store.snapshot(w.id)).nodes.length,5)
 preview=await store.deletionPreview(grandchild.id)
 await store.deleteNode(grandchild.id,preview.token)
 preview=await store.deletionPreview(child.id)
 const deleted=await store.deleteNode(child.id,preview.token)
 assert.equal(deleted.length,2,'previously deleted descendant keeps separate batch')
 assert.equal((await store.snapshot(w.id)).nodes.length,2)
 const trashEntries = await store.deletedNodes()
 assert.equal(trashEntries.length,3)
 const entry = trashEntries.find(n => n.id === grandchild.id)
 assert.equal(entry.workspaceName,'trash-test')
 assert.deepEqual(entry.pathTitles,['root','child','grandchild'])
 assert.equal(entry.pathComplete,true)
 await add('new root after deletion')
 assert.equal((await store.deletedNodes()).length,3,'creating nodes must preserve trash')
 assert.equal((await store.search(w.id,'evidence')).length,0)
 await assert.rejects(store.getThread(child.threadId),/E_NOT_FOUND/)
 await assert.rejects(store.createNode({workspaceId:w.id,parentId:child.id,title:'invalid'}),/E_NOT_FOUND/)
 assert.deepEqual(await store.deleteNode(child.id,preview.token),deleted)
 await assert.rejects(store.bindSession(sibling.id,'original-session'),/E_CONFLICT/)
 await assert.rejects(store.restoreNode(grandchild.id),/E_CONFLICT/)
 const fresh = new AtlasStore(root)
 assert.equal((await fresh.deletedNodes()).length,3,'restart preserves trash')
 await fresh.restoreNode(child.id)
 assert.equal((await fresh.getNode(child.id)).parentId,parent.id)
 assert.equal((await fresh.getNode(child.id)).sessionId,'original-session')
 assert.equal((await fresh.getNode(child.id)).position.x,child.position.x)
 assert.equal((await fresh.deletedNodes()).length,1)
 await fresh.restoreNode(grandchild.id)
 assert.equal((await fresh.getThread(child.threadId)).messages[0].content,'original evidence')
 assert.equal(await readFile(messageFile,'utf8'),messages)
 assert.equal(await readFile(cardFile,'utf8'),card)
 assert.equal((await fresh.getThread(child.threadId)).card.tldr,'retained card')
 assert.equal(await readFile(join(dir,'result.txt'),'utf8'),'original file')
 assert.deepEqual(await fresh.restoreNode(child.id),[])
 const plan=await fresh.deletionPreview(parent.id)
 await Promise.all([fresh.deleteNode(parent.id,plan.token),fresh.deleteNode(parent.id,plan.token)])
 assert.equal((await fresh.snapshot(w.id)).nodes.length,1)
 await fresh.restoreNode(parent.id)
 assert.equal((await fresh.snapshot(w.id)).nodes.length,6)
 const purgePlan=await fresh.deletionPreview(child.id)
 await fresh.deleteNode(child.id,purgePlan.token)
 const batch=(await fresh.deletedNodes()).find(n=>n.id===child.id).deletionBatchId
 await assert.rejects(fresh.purgeNode(child.id,'wrong-batch'),/E_CONFLICT/)
 await assert.rejects(fresh.purgeNode(child.id,batch,async()=>{throw new Error('cleanup failed')}),/cleanup failed/)
 assert.ok((await fresh.getNode(child.id,true)).deletedAt,'cleanup failure keeps node retryable')
 const purged=await fresh.purgeNode(child.id,batch)
 assert.ok(purged.includes(child.id))
 await assert.rejects(fresh.getNode(child.id,true),/E_NOT_FOUND/)
 const retained=(await new AtlasStore(root).deletedNodes()).find(n=>n.id===child.id)
 assert.equal(retained.sessionId,'original-session')
 assert.ok(retained.purgedAt)
 assert.equal(await readFile(messageFile,'utf8'),messages)
 assert.equal(await readFile(cardFile,'utf8'),card)
 assert.equal(await readFile(join(dir,'result.txt'),'utf8'),'original file')
 const otherParent=await add('other parent')
 const otherChild=await add('other child',otherParent.id)
 let otherPlan=await fresh.deletionPreview(otherChild.id)
 await fresh.deleteNode(otherChild.id,otherPlan.token)
 otherPlan=await fresh.deletionPreview(otherParent.id)
 await fresh.deleteNode(otherParent.id,otherPlan.token)
 const otherBatch=(await fresh.deletedNodes()).find(n=>n.id===otherParent.id).deletionBatchId
 await assert.rejects(fresh.purgeNode(otherParent.id,otherBatch),/E_CONFLICT/)
 assert.ok((await fresh.deletedNodes()).some(n=>n.id===otherChild.id))
 const childBatch=(await fresh.deletedNodes()).find(n=>n.id===otherChild.id).deletionBatchId
 await fresh.purgeNodes([{id:otherParent.id,batchId:otherBatch},{id:otherChild.id,batchId:childBatch}])
 await assert.rejects(fresh.getNode(otherParent.id,true),/E_NOT_FOUND/)
 await assert.rejects(fresh.getNode(otherChild.id,true),/E_NOT_FOUND/)
 await fresh.dismissSessions([child.id])
 assert.equal((await new AtlasStore(root).deletedNodes()).find(n=>n.id===child.id).sessionId,undefined)
 assert.equal((await fresh.deletedNodes(true)).find(n=>n.id===child.id).sessionId,'original-session','old list-only removal remains recoverable for native archive')
 await assert.rejects(fresh.dismissSessions([child.id],async()=>{throw new Error('archive failed')}),/archive failed/)
 assert.equal(await readFile(join(dir,'result.txt'),'utf8'),'original file')
 console.log('Trash: subtree/CAS/retry/restart/restore/binding/message/file preservation passed')
} finally {await rm(root,{recursive:true,force:true})}
