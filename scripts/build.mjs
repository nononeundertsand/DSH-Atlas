/**
 * 构建 DSH-Atlas 的两个半边：
 * - lib/host/index.js  Host 插件（ESM，Node）
 * - lib/client.js      浏览器插件（CJS，包进 DSH 的 __ModuleLoader__ 协议）
 *
 * 浏览器依赖 React/React JSX Runtime 等由 DSH 平台模块表提供，不打包进来。
 */
import { build, context } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const watch = process.argv.includes('--watch')

/** DSH 浏览器平台自带的共享模块，必须保持外部依赖。 */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  'zod',
  '@tanstack/react-virtual',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

async function buildHost() {
  await build({
    absWorkingDir: root,
    entryPoints: ['src/host/index.ts'],
    outfile: 'lib/host/index.js',
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    sourcemap: true,
    packages: 'external',
    logLevel: 'info',
  })
}

async function buildClient() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/client/index.tsx'],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: PLATFORM_MODULES,
    logLevel: 'silent',
  })

  const bundle = result.outputFiles[0]?.text
  if (!bundle) throw new Error('client bundle was not produced')

  const wrapped = `/**
 * Generated by scripts/build.mjs — edit src/client/** instead.
 * DSH 浏览器插件协议：脚本只注册工厂，模块体在首次物化时执行。
 */
window.__ModuleLoader__.load({
  id: "dsh-atlas",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${indent(bundle, 4)}
    return module.exports;
  }
});
`

  await mkdir(join(root, 'lib'), { recursive: true })
  await writeFile(join(root, 'lib/client.js'), wrapped, 'utf8')
  console.log(`  lib/client.js  ${(wrapped.length / 1024).toFixed(1)}kb`)
}

function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .split('\n')
    .map((line) => (line ? pad + line : line))
    .join('\n')
}

if (watch) {
  const host = await context({
    absWorkingDir: root,
    entryPoints: ['src/host/index.ts'],
    outfile: 'lib/host/index.js',
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    sourcemap: true,
    packages: 'external',
    logLevel: 'info',
  })
  await host.watch()
  console.log('watching host; run `npm run build` once more for client changes')
} else {
  await buildHost()
  await buildClient()
}
